// Builds src/ui/glyphData.ts from Phosphor icon definitions: for each icon
// the app uses (scripts/glyphs.json), only the weights it is drawn in.
// Run: node scripts/gen-glyphs.mjs (needs @phosphor-icons/react installed).
import { readFileSync, writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const spec = JSON.parse(readFileSync(new URL("./glyphs.json", import.meta.url), "utf8"));
const out = {};
for (const [name, { ph, weights }] of Object.entries(spec)) {
  const defs = (await import(new URL(`../node_modules/@phosphor-icons/react/dist/defs/${ph}.es.js`, import.meta.url).href)).default;
  out[name] = {};
  for (const w of weights) {
    const el = defs.get(w);
    if (!el) throw new Error(`${ph} has no ${w}`);
    out[name][w] = renderToStaticMarkup(createElement("g", null, el)).replace(/^<g>|<\/g>$/g, "");
  }
}
const body = Object.entries(out)
  .map(([n, ws]) => `  ${n}: {${Object.entries(ws).map(([w, svg]) => ` ${w}: ${JSON.stringify(svg)}`).join(",")} }`)
  .join(",\n");
writeFileSync(
  new URL("../src/ui/glyphData.ts", import.meta.url),
  `/* Generated by scripts/gen-glyphs.mjs from Phosphor Icons (MIT). Do not edit by hand. */\nexport type GlyphWeight = "regular" | "bold" | "fill" | "duotone";\nexport const GLYPHS: Record<string, Partial<Record<GlyphWeight, string>>> = {\n${body}\n};\n`
);
console.log(Object.keys(out).length, "icons");
